#ifndef OPENMX_MGPU_BAND_PLAN_H
#define OPENMX_MGPU_BAND_PLAN_H

#include <limits.h>
#include <stdint.h>

/* Count the k-points actually evaluated by the main Band solvers, before
   HIP/OpenMP initializes rank-local storage. Collinear meshes pair k and
   -k; noncollinear meshes evaluate every point. Special collinear meshes
   use the list already generated by Input_std. Zero declines invalid or
   unrepresentable plans without changing the existing input diagnostics. */
static inline int openmx_mgpu_band_kpoint_count(int spin, int generation,
                                               int nx, int ny, int nz,
                                               int special_count)
{
    int64_t count, fixed;
    if (nx <= 0 || ny <= 0 || nz <= 0) return 0;
    count = (int64_t)nx * ny;
    if (count > INT_MAX || count > INT_MAX / nz) return 0;
    count *= nz;
    if (spin == 3) return (int)count;
    if (spin != 0 && spin != 1) return 0;
    if (generation == 2) return special_count > 0 ? special_count : 0;
    if (generation == 1) {
        fixed = (nx % 2) * (ny % 2) * (nz % 2);
    } else if (generation == 3) {
        fixed = (1 + (nx % 2 == 0)) * (1 + (ny % 2 == 0)) *
                (1 + (nz % 2 == 0));
    } else return 0;
    return (int)((count + fixed) / 2);
}

#endif
