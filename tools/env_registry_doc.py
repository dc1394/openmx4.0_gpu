#!/usr/bin/env python3
"""Generate the environment-variable tables of the documentation.

Inputs
  source/openmx_env_registry.h     every name the build reads: id, kind, scope, default
  doc/environment_variables.json   the prose: groups and rows (a row covers one or
                                   more names), English and Japanese, optional
                                   documented defaults

Outputs (rewritten in place; --check only compares)
  doc/OpenMX40_GPU_implementation_en.html   the <tbody> of table 10-1 between the
  doc/OpenMX40_GPU_implementation_ja.html   markers <!-- env-table:begin --> / end
  docs/ENVIRONMENT_VARIABLES.md             the English table as Markdown

Every registered name that openmx reads (kind other than "tool") must appear in
exactly one row, and every row name must be registered: the test suite runs this
tool with --check.
"""
from pathlib import Path
import argparse
import html
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from update_env_registry import parse_registry, REGISTRY  # noqa: E402

DATA = ROOT / "doc" / "environment_variables.json"
HTML_DOCS = {"en": ROOT / "doc" / "OpenMX40_GPU_implementation_en.html", "ja": ROOT / "doc" / "OpenMX40_GPU_implementation_ja.html"}
MARKDOWN = ROOT / "docs" / "ENVIRONMENT_VARIABLES.md"
BEGIN, END = "<!-- env-table:begin -->", "<!-- env-table:end -->"
WORDS = {"auto": {"en": "auto", "ja": "auto"}, "unlimited": {"en": "uncapped", "ja": "制限なし"}, "": {"en": "—", "ja": "—"}}


def load():
    registry = parse_registry(REGISTRY.read_text())
    data = json.loads(DATA.read_text())
    errors = []
    seen = {}
    group_ids = [g["id"] for g in data["groups"]]
    for row in data["rows"]:
        if row["group"] not in group_ids:
            errors.append(f"unknown group {row['group']} for {row['names']}")
        for name in row["names"]:
            if name not in registry:
                errors.append(f"{name} is not registered")
            elif registry[name]["kind"] == "tool":
                errors.append(f"{name} is a build-tool name and does not belong in the table")
            if name in seen:
                errors.append(f"{name} appears twice")
            seen[name] = row
        for name in row.get("defaults", {}):
            if name not in row["names"]:
                errors.append(f"defaults of {row['names']} names {name}")
    for name, e in registry.items():
        if e["kind"] != "tool" and name not in seen:
            errors.append(f"{name} (read by {e['module']}) has no row in {DATA.name}")
    if errors:
        raise SystemExit("\n".join(errors))
    return registry, data


def text_of(value, lang):
    return value[lang] if isinstance(value, dict) else value


def label_of(row, lang):
    if "label" in row:
        return text_of(row["label"], lang)
    return " / ".join(f"<code>{n}</code>" for n in row["names"])


def default_of(row, name, registry, lang):
    documented = row.get("defaults", {}).get(name)
    if documented:
        return html.escape(documented[lang])
    value = registry[name]["default"]
    return WORDS[value][lang] if value in WORDS else html.escape(value)


def default_cell(row, registry, lang):
    if "default_cell" in row:
        return html.escape(row["default_cell"][lang])
    return " / ".join(default_of(row, n, registry, lang) for n in row["names"])


def html_rows(registry, data, lang):
    lines = []
    rows_by_group = {}
    for row in data["rows"]:
        rows_by_group.setdefault(row["group"], []).append(row)
    for group in data["groups"]:
        lines.append(f'<tr><td colspan="3" style="background:#f0f4fa;"><b>{group[lang]}</b></td></tr>')
        for row in rows_by_group.get(group["id"], []):
            lines.append(f"<tr><td>{label_of(row, lang)}</td><td>{default_cell(row, registry, lang)}</td><td>{row[lang]}</td></tr>")
    return "\n".join(lines)


def markdown_table(registry, data):
    def cell(s):
        s = re.sub(r"</?(code|b|i|sup)>", "`", s) if False else s
        s = re.sub(r"<code>(.*?)</code>", r"`\1`", s)
        s = re.sub(r"<b>(.*?)</b>", r"**\1**", s)
        s = re.sub(r"<sup>(.*?)</sup>", r"^\1", s)
        s = re.sub(r"<[^>]+>", "", s)
        return html.unescape(s).replace("|", "\\|").replace("\n", " ")
    lines = ["# Environment variables of the GPU build", "",
             "Generated by `tools/env_registry_doc.py` from `source/openmx_env_registry.h` and `doc/environment_variables.json`;",
             "do not edit by hand. Every setting is read once after `MPI_Init` (`source/openmx_env.c`): rank 0's values reach",
             "every rank, a misspelt `OPENMX_*` name and a value that does not parse for its kind are reported once, and",
             "`level.of.stdout 2` lists the settings in effect. A flag accepts a number (nonzero = on), `on`/`yes`/`true`",
             "and `off`/`no`/`false`; `auto`, an empty value and an unset variable select the default.", ""]
    rows_by_group = {}
    for row in data["rows"]:
        rows_by_group.setdefault(row["group"], []).append(row)
    for group in data["groups"]:
        lines += [f"## {cell(group['en'])}", "", "| Variable | Default | Meaning |", "|---|---|---|"]
        for row in rows_by_group.get(group["id"], []):
            lines.append(f"| {cell(label_of(row, 'en'))} | {cell(default_cell(row, registry, 'en'))} | {cell(row['en'])} |")
        lines.append("")
    return "\n".join(lines)


def replace_between(text, begin, end, body):
    start = text.find(begin)
    stop = text.find(end)
    if start < 0 or stop < 0 or stop < start:
        raise SystemExit(f"markers {begin} / {end} not found")
    start += len(begin)
    return text[:start] + "\n" + body + "\n" + text[stop:]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when a generated file would change")
    args = parser.parse_args()
    registry, data = load()
    changed = []
    for lang, path in HTML_DOCS.items():
        old = path.read_text()
        new = replace_between(old, BEGIN, END, html_rows(registry, data, lang))
        if new != old:
            changed.append(path)
            if not args.check:
                path.write_text(new)
    markdown = markdown_table(registry, data)
    if not MARKDOWN.is_file() or MARKDOWN.read_text() != markdown:
        changed.append(MARKDOWN)
        if not args.check:
            MARKDOWN.write_text(markdown)
    names = sum(len(r["names"]) for r in data["rows"])
    if args.check:
        if changed:
            print("out of date: " + ", ".join(str(p.relative_to(ROOT)) for p in changed))
            return 1
        print(f"environment tables up to date ({len(data['rows'])} rows, {names} names)")
        return 0
    print(f"{len(data['rows'])} rows, {names} names; " + ("rewrote " + ", ".join(str(p.relative_to(ROOT)) for p in changed) if changed else "nothing changed"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
